const format = (template: string, params?: Record<string, string | number>): string =>
    params
        ? template.replace(/\{(\w+)\}/g, (match, name: string) =>
              params[name] === undefined ? match : String(params[name]),
          )
        : template;

export function translate(
    locale: Locale,
    key: TranslationKey,
    params?: Record<string, string | number>,
): string {
    const dictionary = locale === "en" ? en : zh;
    return format(dictionary[key] ?? zh[key] ?? key, params);
}

export type Translate = (key: TranslationKey, params?: Record<string, string | number>) => string;

interface I18nContextValue {
    locale: Locale;
    setLocale: (locale: Locale) => void;
    t: Translate;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const readStoredLocale = (): Locale => {
    try {
        return window.localStorage.getItem(LOCALE_STORAGE_KEY) === "en" ? "en" : "zh";
    } catch {
        return "zh";
    }
};

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [locale, setLocale] = useState<Locale>(readStoredLocale);

    useEffect(() => {
        document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
        try {
            window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
        } catch {
            // 隐私模式下 localStorage 可能不可用，语言仍在本会话内生效
        }
    }, [locale]);

    const t = useCallback<Translate>((key, params) => translate(locale, key, params), [locale]);
    const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nContextValue {
    const value = useContext(I18nContext);
    if (!value) throw new Error("useI18n must be used inside I18nProvider");
    return value;
}
